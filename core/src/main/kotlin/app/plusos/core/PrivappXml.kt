package app.plusos.core

/**
 * `/product/etc/permissions/privapp-permissions-plus.xml`: grants exactly the privileged permissions of chosen add-ons,
 * and [denies] the rest an own app requests (so the platform's enforce mode accepts the image).
 */
object PrivappXml {
    fun generate(grants: Map<String, List<String>>, denies: Map<String, List<String>> = emptyMap()): String = buildString {
        append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        append("<!-- Generated by +PLUS for GrapheneOS. Not affiliated with or endorsed by the GrapheneOS project. -->\n")
        append("<permissions>\n")
        for (pkg in (grants.keys + denies.keys).sorted()) {
            require(pkg.matches(Regex("[A-Za-z0-9_.]+"))) { "bad package name '$pkg'" }
            append("    <privapp-permissions package=\"").append(pkg).append("\">\n")
            for (perm in grants[pkg].orEmpty().toSortedSet()) {
                require(perm.matches(Regex("[A-Za-z0-9_.]+"))) { "bad permission name '$perm'" }
                append("        <permission name=\"").append(perm).append("\"/>\n")
            }
            for (perm in denies[pkg].orEmpty().toSortedSet() - grants[pkg].orEmpty().toSet()) {
                require(perm.matches(Regex("[A-Za-z0-9_.]+"))) { "bad permission name '$perm'" }
                append("        <deny-permission name=\"").append(perm).append("\"/>\n")
            }
            append("    </privapp-permissions>\n")
        }
        append("</permissions>\n")
    }
}
